-- A "planta" do banco do Lovable: cada objeto do esquema `public` (e os
-- gatilhos e regras que ele põe em `auth` e `storage`) como uma linha
-- (ordem, sql), lida dos catálogos do Postgres — o que EXISTE lá hoje.
--
-- ── Por que não reaplicar as migrations ───────────────────────────────────
--
-- O repositório tem 175 migrations, mas só 81 estão no histórico do Lovable:
-- as outras foram aplicadas por cópias com outro nome, à mão ou em outra
-- ordem. Reaplicadas em sequência num banco vazio, quebram logo na 10ª
-- (`clinic_chairs` criada por duas migrations com colunas diferentes). A
-- planta reproduz o resultado, não a história.
--
-- Só leitura. `montar-banco.mjs` aplica as linhas no banco novo em passadas:
-- o que falha por depender de algo ainda não criado (função que devolve uma
-- tabela, valor padrão que chama função) entra na passada seguinte.
--
-- Fora daqui, de propósito: dados, `cron.job` (ver rotinas.sql), cofre.

WITH
rel AS (
  SELECT c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity,
         c.relreplident, c.reloptions, c.relacl
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'e')
),
func AS (
  SELECT p.oid, p.proacl, p.oid::regprocedure::text AS assinatura
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
),
linhas(ordem, sql) AS (
  -- Extensões (as que o Supabase já instala viram no-op).
  SELECT 0, format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname)
  FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
  WHERE e.extname NOT IN ('plpgsql')

  UNION ALL -- Tipos enumerados
  SELECT 10, format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
    (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) FROM pg_enum e WHERE e.enumtypid = t.oid))
  FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = 'public' AND t.typtype = 'e'

  UNION ALL -- Sequências soltas (as de IDENTITY nascem com a coluna)
  SELECT 20, format('CREATE SEQUENCE IF NOT EXISTS public.%I;', r.relname)
  FROM rel r WHERE r.relkind = 'S'
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = r.oid AND d.deptype = 'i')

  UNION ALL -- Tabelas: colunas, tipos, padrões, NOT NULL, identidade, geradas
  SELECT 30, format('CREATE TABLE public.%I (%s);', r.relname, (
    SELECT string_agg(
      format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
      || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                            WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
      || CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
              WHEN ad.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) ELSE '' END
      || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
      ', ' ORDER BY a.attnum)
    FROM pg_attribute a
    LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    WHERE a.attrelid = r.oid AND a.attnum > 0 AND NOT a.attisdropped))
  FROM rel r WHERE r.relkind IN ('r', 'p')

  UNION ALL -- Sequência pertencendo à coluna (serial)
  SELECT 35, format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', s.relname, t.relname, a.attname)
  FROM pg_depend d
  JOIN rel s ON s.oid = d.objid AND s.relkind = 'S'
  JOIN pg_class t ON t.oid = d.refobjid
  JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
  WHERE d.deptype = 'a'

  UNION ALL -- Funções, com SECURITY DEFINER, search_path e corpo como estão
  SELECT 40, pg_get_functiondef(f.oid) || ';' FROM func f

  UNION ALL -- Chave primária, únicas, checagens e exclusões
  SELECT 50, format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', r.relname, c.conname, pg_get_constraintdef(c.oid))
  FROM pg_constraint c JOIN rel r ON r.oid = c.conrelid
  WHERE c.contype IN ('p', 'u', 'c', 'x')

  UNION ALL -- Chaves estrangeiras, depois de todas as tabelas
  SELECT 55, format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', r.relname, c.conname, pg_get_constraintdef(c.oid))
  FROM pg_constraint c JOIN rel r ON r.oid = c.conrelid
  WHERE c.contype = 'f'

  UNION ALL -- Índices que não nascem de uma constraint
  SELECT 60, pg_get_indexdef(i.indexrelid) || ';'
  FROM pg_index i JOIN rel r ON r.oid = i.indrelid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)

  UNION ALL -- Views
  SELECT 70, format('CREATE VIEW public.%I%s AS %s', r.relname,
    COALESCE(' WITH (' || array_to_string(r.reloptions, ', ') || ')', ''), pg_get_viewdef(r.oid, true))
  FROM rel r WHERE r.relkind = 'v'

  UNION ALL -- Gatilhos que chamam funções nossas, em qualquer esquema
  SELECT 80, pg_get_triggerdef(t.oid) || ';'
  FROM pg_trigger t
  JOIN pg_proc p ON p.oid = t.tgfoid
  JOIN pg_namespace pn ON pn.oid = p.pronamespace
  WHERE NOT t.tgisinternal AND pn.nspname = 'public'

  UNION ALL -- Segurança por linha
  SELECT 90, format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', r.relname)
  FROM rel r WHERE r.relkind IN ('r', 'p') AND r.relrowsecurity
  UNION ALL
  SELECT 90, format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', r.relname)
  FROM rel r WHERE r.relkind IN ('r', 'p') AND r.relforcerowsecurity

  UNION ALL -- Regras de acesso (as de `storage.objects` são as dos 3 depósitos)
  SELECT 95, format('DROP POLICY IF EXISTS %I ON %I.%I; CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
    p.policyname, p.schemaname, p.tablename,
    p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
    (SELECT string_agg(CASE WHEN x = 'public' THEN 'public' ELSE quote_ident(x) END, ', ') FROM unnest(p.roles) x),
    COALESCE(' USING (' || p.qual || ')', ''), COALESCE(' WITH CHECK (' || p.with_check || ')', ''))
  FROM pg_policies p WHERE p.schemaname IN ('public', 'storage')

  UNION ALL -- Permissões das tabelas para os papéis da API
  SELECT 100, format('REVOKE ALL ON public.%I FROM anon, authenticated, service_role;', r.relname)
  FROM rel r WHERE r.relkind IN ('r', 'p', 'v') AND r.relacl IS NOT NULL
  UNION ALL
  SELECT 101, format('GRANT %s ON public.%I TO %I;', string_agg(DISTINCT x.privilege_type, ', '), r.relname, g.rolname)
  FROM rel r, aclexplode(r.relacl) x JOIN pg_roles g ON g.oid = x.grantee
  WHERE r.relkind IN ('r', 'p', 'v') AND g.rolname IN ('anon', 'authenticated', 'service_role')
  GROUP BY r.relname, g.rolname

  UNION ALL -- Permissões das funções (várias são fechadas para anon)
  SELECT 100, format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated, service_role;', f.assinatura)
  FROM func f WHERE f.proacl IS NOT NULL
  UNION ALL
  SELECT 101, format('GRANT EXECUTE ON FUNCTION %s TO %s;', f.assinatura,
    CASE WHEN x.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(g.rolname) END)
  FROM func f, aclexplode(f.proacl) x LEFT JOIN pg_roles g ON g.oid = x.grantee
  WHERE f.proacl IS NOT NULL AND (x.grantee = 0 OR g.rolname IN ('anon', 'authenticated', 'service_role'))

  UNION ALL -- Tempo real
  SELECT 110, format('ALTER TABLE public.%I REPLICA IDENTITY FULL;', r.relname)
  FROM rel r WHERE r.relkind = 'r' AND r.relreplident = 'f'
  UNION ALL
  SELECT 111, format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I;', pt.tablename)
  FROM pg_publication_tables pt WHERE pt.pubname = 'supabase_realtime' AND pt.schemaname = 'public'
)
SELECT ordem, sql FROM linhas
